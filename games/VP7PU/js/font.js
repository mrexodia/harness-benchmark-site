export const FONT_W = 5;
export const FONT_H = 7;
const ADVANCE = FONT_W + 1; // one pixel letter spacing

export function textWidth(str, scale = 1) {
  const n = String(str).length;
  return n > 0 ? (n * ADVANCE - 1) * scale : 0;
}

// Draw text with crisp pixel blocks. `anchor` supports left/center/right.
export function drawText(ctx, str, x, y, color, scale = 1, anchor = 'left', alpha = 1) {
  const s = String(str).toUpperCase();
  const w = textWidth(s, scale);
  let px = Math.round(x);
  if (anchor === 'center') px = Math.round(x - w / 2);
  else if (anchor === 'right') px = Math.round(x - w);

  if (alpha !== 1) ctx.globalAlpha = alpha;
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const glyph = G[s[i]] || G['?'];
    const gx = px + i * ADVANCE * scale;
    for (let ry = 0; ry < FONT_H; ry++) {
      const row = glyph[ry];
      for (let rx = 0; rx < FONT_W; rx++) {
        if (row[rx] === '1') {
          ctx.fillRect(gx + rx * scale, Math.round(y) + ry * scale, scale, scale);
        }
      }
    }
  }
  if (alpha !== 1) ctx.globalAlpha = 1;
  return w;
}

// Text with a hard one-pixel (scaled) dark drop shadow, for legibility.
export function drawTextShadow(ctx, str, x, y, color, scale = 1, anchor = 'left', shadow = '#0b1014') {
  drawText(ctx, str, x + scale, y + scale, shadow, scale, anchor);
  drawText(ctx, str, x, y, color, scale, anchor);
}

// Width (in device pixels) of a rendered string.
export function measureText(str, scale, spacing = 1) {
  str = String(str);
  if (!str.length) return 0;
  const adv = 5 * scale + spacing * scale;
  return str.length * adv - spacing * scale;
}

function paint(ctx, str, x, y, scale, color, spacing) {
  const adv = 5 * scale + spacing * scale;
  let cx = x;
  ctx.fillStyle = color;
  for (const raw of str) {
    const glyph = GLYPHS[raw] || GLYPHS['?'];
    for (let row = 0; row < 7; row++) {
      const line = glyph[row];
      for (let col = 0; col < 5; col++) {
        if (line[col] === '#') {
          ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cx += adv;
  }
}

// Draw pixel text. opts: { align, spacing, shadow: {dx,dy,color}, outline: color }
export function drawText(ctx, str, x, y, scale, color, opts = {}) {
  str = String(str).toUpperCase();
  const { align = 'left', spacing = 1, shadow = null, outline = null } = opts;
  let sx = x;
  const w = measureText(str, scale, spacing);
  if (align === 'center') sx = x - Math.floor(w / 2);
  else if (align === 'right') sx = x - w;
  sx = Math.round(sx);
  y = Math.round(y);

  if (outline) {
    for (const [dx, dy] of [[-scale, 0], [scale, 0], [0, -scale], [0, scale]]) {
      paint(ctx, str, sx + dx, y + dy, scale, outline, spacing);
    }
  }
  if (shadow) {
    paint(ctx, str, sx + (shadow.dx || 0), y + (shadow.dy || 0), scale, shadow.color, spacing);
  }
  paint(ctx, str, sx, y, scale, color, spacing);
  return w;
}

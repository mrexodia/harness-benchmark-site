const GLYPH_W = 5;
const GLYPH_H = 7;

// Draw text at (x,y) top-left. `scale` = integer pixel multiplier.
// opt: { align: 'left'|'center'|'right', tracking: extra px per char (in font px), shadow: color }
export function textWidth(str, scale = 2, tracking = 1) {
  if (!str.length) return 0;
  return (str.length * GLYPH_W + (str.length - 1) * tracking) * scale;
}

export function drawText(ctx, str, x, y, scale = 2, color = '#fff', opt = {}) {
  const tracking = opt.tracking === undefined ? 1 : opt.tracking;
  const align = opt.align || 'left';
  const up = String(str).toUpperCase();
  const w = textWidth(up, scale, tracking);
  let sx = x;
  if (align === 'center') sx = Math.round(x - w / 2);
  else if (align === 'right') sx = Math.round(x - w);
  sx = Math.round(sx);
  const sy = Math.round(y);
  ctx.fillStyle = color;
  for (let i = 0; i < up.length; i++) {
    const rows = G[up[i]] || G[' '];
    const gx = sx + i * (GLYPH_W + tracking) * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      let run = 0;
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '1') { run++; }
        else if (run) { ctx.fillRect(gx + (c - run) * scale, sy + r * scale, run * scale, scale); run = 0; }
      }
      if (run) ctx.fillRect(gx + (GLYPH_W - run) * scale, sy + r * scale, run * scale, scale);
    }
  }
  return w;
}

export { GLYPH_W, GLYPH_H };

const GW = 5, GH = 7;

// Measure rendered width in canvas pixels for a given pixel scale.
export function textWidth(text, s = 1) {
  if (!text.length) return 0;
  return text.length * (GW * s + s) - s;
}

// Draw pixel text. scale is the size of one art pixel in target pixels.
export function drawText(ctx, text, x, y, scale = 1, color = '#fff', opts = {}) {
  const t = String(text).toUpperCase();
  const gap = scale;
  let cx = Math.round(x);
  const cy = Math.round(y);
  if (opts.shadow) {
    const sx = opts.shadowX ?? scale, sy = opts.shadowY ?? scale;
    paint(ctx, t, cx + sx, cy + sy, scale, opts.shadow, gap);
  }
  paint(ctx, t, cx, cy, scale, color, gap);
  if (opts.outline) {
    const o = opts.outline;
    for (const [dx, dy] of [[-scale,0],[scale,0],[0,-scale],[0,scale]]) {
      paint(ctx, t, cx + dx, cy + dy, scale, o, gap);
    }
    paint(ctx, t, cx, cy, scale, color, gap);
  }
  return textWidth(t, scale);
}

function paint(ctx, t, x, y, s, color, gap) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of t) {
    const g = G[ch];
    if (g) {
      for (let r = 0; r < GH; r++) {
        const row = g[r];
        for (let c = 0; c < GW; c++) {
          if (row[c] === '#') ctx.fillRect(cx + c * s, y + r * s, s, s);
        }
      }
    }
    cx += GW * s + gap;
  }
}

export function drawTextCenter(ctx, text, cx, y, scale, color, opts) {
  const w = textWidth(String(text).toUpperCase(), scale);
  drawText(ctx, text, cx - w / 2, y, scale, color, opts);
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(str, scale = 1) {
  if (!str.length) return 0;
  return (str.length * (GLYPH_W + 1) - 1) * scale;
}

// Draw pixel text. Options: color, scale, align ('left'|'center'|'right'), shadow, shadowColor
export function drawText(ctx, str, x, y, opts = {}) {
  const scale = opts.scale || 1;
  const color = opts.color || '#ffffff';
  str = String(str).toUpperCase();
  let ox = x;
  if (opts.align === 'center') ox = x - textWidth(str, scale) / 2;
  else if (opts.align === 'right') ox = x - textWidth(str, scale);
  ox = Math.round(ox); y = Math.round(y);

  const paint = (dx, dy, col) => {
    ctx.fillStyle = col;
    let cx = ox + dx;
    for (const ch of str) {
      const g = G[ch] || G['?'];
      for (let r = 0; r < GLYPH_H; r++) {
        const row = g[r];
        for (let c = 0; c < GLYPH_W; c++) {
          if (row[c] === '#') ctx.fillRect(cx + c * scale, y + dy + r * scale, scale, scale);
        }
      }
      cx += (GLYPH_W + 1) * scale;
    }
  };

  if (opts.shadow) paint(scale, scale, opts.shadowColor || 'rgba(20,14,12,0.85)');
  paint(0, 0, color);
}

export function measure(str, scale = 1) { return textWidth(str, scale); }

export function textWidth(text, scale, spacing = 1) {
  let w = 0;
  const step = (5 + spacing) * scale;
  for (const ch of text) {
    if (ch === '\n') continue;
    w += step;
  }
  return Math.max(0, w - spacing * scale);
}

export function drawText(ctx, text, x, y, scale, color, spacing = 1, alpha = 1) {
  const step = (5 + spacing) * scale;
  let cx = x;
  const prev = ctx.globalAlpha;
  ctx.globalAlpha = prev * alpha;
  ctx.fillStyle = color;
  const lines = String(text).toUpperCase().split('\n');
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li];
    let px = cx;
    for (const ch of line) {
      const g = G[ch];
      if (g) {
        for (let row = 0; row < 7; row++) {
          const bits = g[row];
          for (let col = 0; col < 5; col++) {
            if (bits[col] === '#') {
              ctx.fillRect(px + col * scale, y + li * (7 + spacing) * scale, scale, scale);
            }
          }
        }
      }
      px += step;
    }
  }
  ctx.globalAlpha = prev;
  return cx;
}

export function drawTextCentered(ctx, text, cx, y, scale, color, spacing = 1, alpha = 1) {
  const w = textWidth(text, scale, spacing);
  return drawText(ctx, text, Math.round(cx - w / 2), y, scale, color, spacing, alpha);
}

export function drawTextShadow(ctx, text, x, y, scale, color, shadow = '#101820', spacing = 1) {
  drawText(ctx, text, x + scale, y + scale, scale, shadow, spacing, 0.6);
  drawText(ctx, text, x, y, scale, color, spacing);
}

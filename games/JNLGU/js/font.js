const SPACE_ADVANCE = 4; // in font pixels
const GLYPH_ADVANCE = 6;
const GLYPH_W = 5;
const GLYPH_H = 7;

// Parse into row bitmasks (bit 4 = leftmost pixel).
const PARSED = {};
for (const [ch, rows] of Object.entries(GLYPHS)) {
  PARSED[ch] = rows.map((row) => {
    let mask = 0;
    for (let i = 0; i < GLYPH_W; i++) {
      if (row[i] === '#') mask |= 1 << (GLYPH_W - 1 - i);
    }
    return mask;
  });
}

function advance(ch) {
  return ch === ' ' ? SPACE_ADVANCE : GLYPH_ADVANCE;
}

export function textWidth(text, scale = 1) {
  const s = String(text).toUpperCase();
  let w = 0;
  for (const ch of s) w += advance(ch);
  return Math.max(0, (w - 1) * scale);
}

export function textHeight(scale = 1) {
  return GLYPH_H * scale;
}

// Cache rendered text as small canvases so we only rasterize once per string.
const cache = new Map();

function rasterize(text, scale, color) {
  const w = textWidth(text, scale) + scale; // +1 font px breathing room
  const h = GLYPH_H * scale;
  const cv = document.createElement('canvas');
  cv.width = Math.max(1, w);
  cv.height = Math.max(1, h);
  const g = cv.getContext('2d');
  g.fillStyle = color;
  let penX = 0;
  for (const ch of text) {
    const rows = PARSED[ch];
    if (rows) {
      for (let ry = 0; ry < GLYPH_H; ry++) {
        const mask = rows[ry];
        if (!mask) continue;
        for (let rx = 0; rx < GLYPH_W; rx++) {
          if (mask & (1 << (GLYPH_W - 1 - rx))) {
            g.fillRect((penX + rx) * scale, ry * scale, scale, scale);
          }
        }
      }
    }
    penX += advance(ch);
  }
  return { cv, w };
}

// Draw uppercase bitmap text. align: 'left' | 'center' | 'right'
// Returns the drawn width in pixels.
export function drawText(ctx, text, x, y, scale, color, align = 'left') {
  const s = String(text).toUpperCase().replace(/[\n\r\t]/g, ' ');
  if (s.length === 0) return 0;
  const key = s + '|' + scale + '|' + color;
  let entry = cache.get(key);
  if (!entry) {
    entry = rasterize(s, scale, color);
    cache.set(key, entry);
  }
  let dx = Math.round(x);
  if (align === 'center') dx = Math.round(x - entry.w / 2);
  else if (align === 'right') dx = Math.round(x - entry.w);
  ctx.drawImage(entry.cv, dx, Math.round(y));
  return entry.w;
}

// Draw text with a 1-font-pixel drop shadow (used for legibility over the scene).
export function drawTextShadow(ctx, text, x, y, scale, color, shadow = 'rgba(5,10,16,0.85)', align = 'left') {
  drawText(ctx, text, x + scale, y + scale, scale, shadow, align);
  return drawText(ctx, text, x, y, scale, color, align);
}
